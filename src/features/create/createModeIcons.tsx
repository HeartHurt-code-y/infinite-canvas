/**
 * 创作类型 id → 路径键。
 *
 * 即梦把「音频生成」也放进同一个下拉，而路径集合里那枚键叫 `audio`；
 * 本项目的创作类型 id 叫 `speech`（对应后端的 speech_generation）。
 * 这里做一层别名，避免为了对齐 id 去复制一份路径。
 */
const MODE_ALIAS: Readonly<Record<string, string>> = {
  speech: "audio",
  text: "audio",
};

export interface CreateModeIconProps {
  /** 创作类型 id：image / video / audio / text。 */
  readonly mode: string;
  readonly size?: number;
  readonly className?: string;
}

/**
 * 创作类型图标。
 *
 * 即梦的图标是「实心填充 + currentColor」，因此颜色完全跟随所在文字色
 * （创作类型是品牌蓝，模型名是白色）。这里保持同样语义。
 */
export function CreateModeIcon({ mode, size = 16, className }: CreateModeIconProps) {
  const paths = MODE_PATHS[MODE_ALIAS[mode] ?? mode];
  if (!paths) {
    // 文本生成等没有即梦对应图标的类型，退回项目自有图标层。
    return (
      <Icon
        name="text-aa"
        size="sm"
        {...(className === undefined ? {} : { className })}
        aria-hidden="true"
      />
    );
  }
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      preserveAspectRatio="xMidYMid meet"
      fill="none"
      role="presentation"
      xmlns="http://www.w3.org/2000/svg"
      className={className}
      aria-hidden="true"
    >
      <g>
        {paths.map((d) => (
          <path key={d.slice(0, 24)} data-follow-fill="currentColor" d={d} fill="currentColor" />
        ))}
      </g>
    </svg>
  );
}
